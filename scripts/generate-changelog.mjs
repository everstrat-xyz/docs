import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const changelogRoot = join(root, "content/docs/changelog");

export const changelogCategories = [
  "app",
  "contracts",
  "strategies",
  "automation",
  "data-and-integrations",
];

export function collectChangelogEntries(directory = changelogRoot) {
  return changelogCategories
    .flatMap((slug) => {
      const content = readFileSync(join(directory, `${slug}.mdx`), "utf8");
      return [
        ...content.matchAll(/<ChangeEntry\b[^>]*>[\s\S]*?<\/ChangeEntry>/g),
      ]
        .filter(([entry]) => /^## \d{4}-\d{2}-\d{2}$/m.test(entry))
        .map(([entry]) => ({
          slug,
          date: entry.match(/^## (\d{4}-\d{2}-\d{2})$/m)[1],
          entry,
        }));
    })
    .sort((a, b) => b.date.localeCompare(a.date));
}

export function createChangelogIndex(directory = changelogRoot) {
  const entries = collectChangelogEntries(directory);
  if (!entries.length) throw new Error("Changelog has no dated entries.");
  const formatDate = (date) =>
    new Intl.DateTimeFormat("en", {
      dateStyle: "long",
      timeZone: "UTC",
    }).format(new Date(`${date}T00:00:00Z`));
  const feed = entries.map(({ slug, date, entry }) => {
    // Fragment links in an entry belong to its canonical category page.
    const linked = entry
      .replaceAll("](#", `](/changelog/${slug}#`)
      .replaceAll('href="#', `href="/changelog/${slug}#`);
    return linked.replace(
      "</ChangeEntry>",
      `[View in ${slug === "data-and-integrations" ? "Data & integrations" : slug[0].toUpperCase() + slug.slice(1)}](/changelog/${slug}#${date})\n\n</ChangeEntry>`,
    );
  });

  return `---
title: Changelog
description: New features, improvements, and fixes across Everstrat.
---

{/* Generated by scripts/generate-changelog.mjs. Edit the category pages. */}

<span id="latest-updates" />

All **${entries.length} dated updates** across five components, from ${formatDate(entries.at(-1).date)} to ${formatDate(entries[0].date)}. Dates are UTC.

${feed.join("\n\n")}

<details className="change-details">
<summary>About this history & verification</summary>

This feed contains every dated entry from the five category histories, including pre-extraction app commits from March 2026. Entries are maintained in their category pages and combined automatically here.

Released entries have a successful app Production deployment; On-chain entries have an execution receipt. Code merged and Source update entries record implementation work, not a verified production activation date.

Reviewed on October 15, 2026: \`app\` through \`47c0756\`, \`contracts\` through \`157129b\`, \`keepers\` through \`ec1ab3f\`, and \`governance\` through \`047f8e3\`. Some source links require organization access.

For dated protocol state, use [Current deployments](/operations/current-deployments). Addresses live in [Contract addresses](/reference/contract-addresses). Research experiments in \`backtests\` do not establish a live strategy. See the [release notes policy](/contributing/changelog-or-release-notes-strategy) for maintenance rules.

</details>
`;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const path = join(changelogRoot, "index.mdx");
  const next = createChangelogIndex();
  if (readFileSync(path, "utf8") !== next) writeFileSync(path, next);
  console.log(`Changelog: ${collectChangelogEntries().length} dated updates.`);
}
