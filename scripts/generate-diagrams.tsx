import { mkdir, readFile, writeFile } from "node:fs/promises";
import { renderToStaticMarkup } from "react-dom/server";
import { DocsDiagram } from "../components/docs-diagram";
import { type DiagramName, diagrams } from "../lib/diagrams";

const css = await readFile(
  new URL("../components/docs-diagram.css", import.meta.url),
  "utf8",
);
const output = new URL("../public/diagrams/", import.meta.url);
await mkdir(output, { recursive: true });
const darkTokens = css.match(/\.dark \.docs-diagram \{([^}]+)\}/)?.[1];
if (!darkTokens) throw new Error("Missing dark diagram tokens");

for (const name of Object.keys(diagrams) as DiagramName[]) {
  const spec = diagrams[name];
  const figure = renderToStaticMarkup(<DocsDiagram name={name} standalone />);
  // HTML escapes text via React before interpolation into the document.
  const title = renderToStaticMarkup(
    <title>{`${spec.title} | Everstrat`}</title>,
  );
  const html = `<!doctype html>
<!-- Generated by bun run diagrams:gen. Edit lib/diagrams.ts and components/docs-diagram.* instead. -->
<html lang="en" class="diagram-document">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
${title}
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&amp;display=swap" rel="stylesheet">
<style>
* { box-sizing: border-box; }
body { margin: 0; padding: 32px 16px; background: #f5f4f3; font-family: Inter, system-ui, sans-serif; }
main { width: 100%; max-width: ${spec.width + 2}px; min-width: 0; margin: 0 auto; }
.docs-diagram { margin: 0; }
${css}
@media (prefers-color-scheme: dark) {
  body { background: #191b1a; color-scheme: dark; }
  .diagram-document .docs-diagram {${darkTokens} }
}
</style>
</head>
<body><main>${figure}</main></body>
</html>
`;
  await writeFile(new URL(`${name}.html`, output), html);
}
console.log(`Generated ${Object.keys(diagrams).length} standalone diagrams.`);
